// Graded exercises for the SQL Playground. A learner's query is checked by
// running the reference solution against the same database and comparing
// result sets (as multisets, or as sequences when `ordered` is set). Column
// names don't matter; column order and values do.
//
// Data-modification exercises set `check`: the learner's statements and the
// reference solution each run inside a transaction that is rolled back, and
// what gets compared is the result of `check` read inside that transaction —
// the state each one left behind. The database itself never changes.

export type SqlSection = "basics" | "aggregation" | "joins" | "subqueries" | "windows" | "patterns" | "dml";

export const SQL_SECTIONS: { id: SqlSection; title: string }[] = [
  { id: "basics", title: "Basics" },
  { id: "aggregation", title: "Aggregation" },
  { id: "joins", title: "Joins" },
  { id: "subqueries", title: "Subqueries, CTEs & sets" },
  { id: "windows", title: "Window functions" },
  { id: "patterns", title: "Interview patterns" },
  { id: "dml", title: "Changing data" },
];

export interface SqlExercise {
  id: string;
  section: SqlSection;
  title: string;
  /** Difficulty, 1 (warm-up) to 4 (interview-hard). */
  level: 1 | 2 | 3 | 4;
  topic: string;
  prompt: string;
  /** Result columns the learner should return (or that `check` returns), in order. */
  columns: string[];
  ordered: boolean;
  hint: string;
  solution: string;
  /** For data-modification exercises: the query that reads the state to compare. */
  check?: string;
  lesson: string;
}

